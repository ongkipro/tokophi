#!/usr/bin/env node
// verify:openapi — Task 5.13 / NF-15. Two claims, both derived, both must hold:
//
//   1. Every operation the OpenAPI corpus DOCUMENTS exists on disk (path + method), so the contract
//      cannot describe a route that was renamed or deleted — `specs/docs/TASKS.md` once asserted
//      "zero implementation drift" from a hand check nobody could re-run.
//   2. Every PUBLIC route on disk — one whose gate is not a seller session, a capability, a platform
//      operator rank or the cron secret — is either documented or named in an EXEMPTION LIST INSIDE
//      THE SPEC FILE (`x-tokophi-route-exemptions`, each entry with a `reason`). The list lives in
//      the contract, not in this script, so an exclusion is a documented decision that ships with the
//      spec and shows up in its diff. This script carries no route names at all.
//
// The route inventory is `specs/docs/page-map.json` (generated by `scripts/gen-page-map.mjs`, kept
// fresh by `test/page-map-fresh.test.ts`) — every API route of all four surfaces with its methods
// and gate. Re-walking the tree here would be a second inventory that could disagree with the first.
//
// Structural validation of each spec (no ambient global tool, no new dependency — `js-yaml` is only
// a transitive package here and a guard must not depend on hoisting): `openapi: 3.x`, `info.title`,
// `info.version`, `paths`, one `operationId` (unique across the corpus) and a `responses` block per
// operation, and every local `$ref` resolving to a key under `components`. It is a KEY-TREE parser
// over indentation, which is all a spec written by hand in this repo's style needs; it does not
// evaluate anchors, flow mappings beyond `[a, b]` lists, or multi-document files.
//
// A spec marked `x-tokophi-status: not-written` (an honest stub awaiting an owner decision — Task
// 5.8) is reported and skipped: it documents nothing and exempts nothing.
//
// Usage: node scripts/verify-openapi.mjs [--spec <file>]... [--page-map <json>]
//   --spec      replace the spec set (default: every *.yaml in specs/openapi/)
//   --page-map  replace the route inventory (default: specs/docs/page-map.json)
// Exit 0 = clean, 1 = drift (a diff-style report on stdout), 2 = usage/parse error.

import { existsSync, readFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join, relative, basename } from "node:path";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const METHODS = new Set(["get", "put", "post", "delete", "options", "head", "patch", "trace"]);
// A gate that proves an IDENTITY or a SHARED SECRET. `public-body`, `rate-limit`, `bot` and
// `callback-auth` are hardening on a public door, not a login — those routes stay public.
const PRIVATE_GATE = /^(session|platform-session|cron|cap:|route:)/;

// ─── args ────────────────────────────────────────────────────────────────────────────────────────
const args = process.argv.slice(2);
const specFiles = [];
let pageMapFile = join(ROOT, "specs/docs/page-map.json");
for (let i = 0; i < args.length; i++) {
  if (args[i] === "--spec") specFiles.push(args[++i]);
  else if (args[i] === "--page-map") pageMapFile = args[++i];
  else {
    console.error(`unknown argument: ${args[i]}`);
    process.exit(2);
  }
}
if (specFiles.length === 0) {
  const dir = join(ROOT, "specs/openapi");
  for (const f of readdirSync(dir).sort()) if (/\.ya?ml$/.test(f)) specFiles.push(join(dir, f));
}

// ─── key-tree YAML parser (keys + scalar tails + `[a, b]` lists; enough for our own specs) ───────
function parseKeyTree(text) {
  const root = { key: "", indent: -1, value: "", children: [], line: 0 };
  const stack = [root];
  const lines = text.split("\n");
  for (let n = 0; n < lines.length; n++) {
    const raw = lines[n];
    if (!raw.trim() || raw.trim().startsWith("#")) continue;
    let indent = raw.match(/^ */)[0].length;
    let body = raw.slice(indent);
    let listItem = false;
    if (body.startsWith("- ")) {
      // `- key: value` opens an anonymous list entry whose keys sit two columns deeper.
      listItem = true;
      indent += 2;
      body = body.slice(2);
    } else if (body === "-") continue;
    const m = body.match(/^("[^"]*"|'[^']*'|[^\s:#][^:]*?):(?:\s+(.*))?$/);
    if (!m) {
      // A block-scalar continuation line (description: |) or a bare list scalar — not a key.
      continue;
    }
    const key = m[1].replace(/^['"]|['"]$/g, "");
    const value = (m[2] ?? "").replace(/\s+#.*$/, "").trim();
    // A new list item must also pop the PREVIOUS item's holder (which sits one column shallower).
    const floor = listItem ? indent - 1 : indent;
    while (stack.length > 1 && stack[stack.length - 1].indent >= floor) stack.pop();
    const parent = stack[stack.length - 1];
    let holder = parent;
    if (listItem) {
      holder = { key: `[${parent.children.length}]`, indent: indent - 1, value: "", children: [], line: n + 1 };
      parent.children.push(holder);
      stack.push(holder);
    }
    const node = { key, indent, value, children: [], line: n + 1 };
    holder.children.push(node);
    stack.push(node);
  }
  return root;
}
const child = (node, key) => node?.children.find((c) => c.key === key);
const listOf = (node) => (node ? node.children.filter((c) => c.key.startsWith("[")) : []);
const scalarList = (v) =>
  v.startsWith("[") ? v.slice(1, -1).split(",").map((s) => s.trim().replace(/^['"]|['"]$/g, "")).filter(Boolean) : v ? [v] : [];

function collectRefs(node, acc) {
  if (node.key === "$ref") acc.push({ ref: node.value.replace(/^['"]|['"]$/g, ""), line: node.line });
  for (const c of node.children) collectRefs(c, acc);
  return acc;
}

// ─── load specs ──────────────────────────────────────────────────────────────────────────────────
const problems = [];
const documented = new Map(); // "METHOD path" → { file, operationId }
const exemptions = []; // { app, path, methods, reason, file, line }
const operationIds = new Map();

for (const file of specFiles) {
  const rel = relative(ROOT, file);
  if (!existsSync(file)) {
    console.error(`spec not found: ${rel}`);
    process.exit(2);
  }
  const tree = parseKeyTree(readFileSync(file, "utf8"));
  const status = child(tree, "x-tokophi-status")?.value;
  if (status === "not-written") {
    console.log(`  skip ${rel} — x-tokophi-status: not-written (stub; documents nothing, exempts nothing)`);
    continue;
  }
  const version = child(tree, "openapi")?.value ?? "";
  if (!/^3\.\d+\.\d+$/.test(version)) problems.push(`${rel}: \`openapi\` must be a 3.x.y version string (got "${version}")`);
  const info = child(tree, "info");
  for (const k of ["title", "version"]) if (!child(info, k)?.value) problems.push(`${rel}: info.${k} is missing`);
  const paths = child(tree, "paths");
  if (!paths) problems.push(`${rel}: no \`paths\` block`);

  for (const p of paths?.children ?? []) {
    if (!p.key.startsWith("/")) continue;
    for (const op of p.children) {
      if (!METHODS.has(op.key)) continue;
      const method = op.key.toUpperCase();
      const id = child(op, "operationId")?.value;
      if (!id) problems.push(`${rel}:${op.line}: ${method} ${p.key} has no operationId`);
      else if (operationIds.has(id)) problems.push(`${rel}:${op.line}: operationId "${id}" duplicates ${operationIds.get(id)}`);
      else operationIds.set(id, `${rel}:${op.line}`);
      if (!child(op, "responses")) problems.push(`${rel}:${op.line}: ${method} ${p.key} has no responses`);
      const key = `${method} ${p.key}`;
      if (documented.has(key)) problems.push(`${rel}:${op.line}: ${key} is documented twice (also ${documented.get(key).file})`);
      documented.set(key, { file: rel, line: op.line, operationId: id });
    }
  }

  // $ref resolution against this file's own components.
  const components = child(tree, "components");
  for (const { ref, line } of collectRefs(tree, [])) {
    if (!ref.startsWith("#/")) {
      problems.push(`${rel}:${line}: external $ref "${ref}" — the corpus is self-contained`);
      continue;
    }
    const segs = ref.slice(2).split("/");
    let node = tree;
    for (const s of segs) node = child(node, s.replace(/~1/g, "/").replace(/~0/g, "~"));
    if (!node) problems.push(`${rel}:${line}: $ref "${ref}" resolves to nothing`);
  }
  if (!components && collectRefs(tree, []).length) problems.push(`${rel}: $refs present but no components block`);

  // Exemptions: an entry is a decision and must say why.
  const ex = child(tree, "x-tokophi-route-exemptions");
  for (const item of listOf(ex)) {
    const app = child(item, "app")?.value;
    const path = child(item, "path")?.value;
    const methods = scalarList(child(item, "methods")?.value ?? "").map((m) => m.toUpperCase());
    const reason = child(item, "reason")?.value ?? "";
    if (!app || !path || methods.length === 0 || reason.length < 20) {
      problems.push(`${rel}:${item.line}: exemption needs app, path, methods and a reason of at least 20 characters`);
      continue;
    }
    exemptions.push({ app, path, methods, reason, file: rel, line: item.line });
  }
}

// ─── route inventory ─────────────────────────────────────────────────────────────────────────────
if (!existsSync(pageMapFile)) {
  console.error(`page map not found: ${pageMapFile} (run: node scripts/gen-page-map.mjs)`);
  process.exit(2);
}
const pageMap = JSON.parse(readFileSync(pageMapFile, "utf8"));
// Next's `[name]` and Astro's `[slug]` are OpenAPI's `{name}`.
const toOpenApiPath = (url) => url.replace(/\[\.\.\.(\w+)\]/g, "{$1}").replace(/\[(\w+)\]/g, "{$1}");
const onDisk = []; // { app, path, method, file, gate, public }
for (const s of pageMap.surfaces) {
  for (const r of s.routes) {
    if (!r.methods?.length) continue;
    const isPublic = !r.gate.some((g) => PRIVATE_GATE.test(g));
    for (const m of r.methods) onDisk.push({ app: s.app, path: toOpenApiPath(r.url), method: m.toUpperCase(), file: r.file, gate: r.gate, public: isPublic });
  }
}
const onDiskKeys = new Set(onDisk.map((r) => `${r.method} ${r.path}`));

// (1) documented → exists
const missing = [...documented.entries()].filter(([key]) => !onDiskKeys.has(key));
// (2) public on disk → documented or exempted
const usedExemptions = new Set();
const undocumented = [];
for (const r of onDisk) {
  if (!r.public) continue;
  const key = `${r.method} ${r.path}`;
  if (documented.has(key)) continue;
  const ex = exemptions.find((e) => e.app === r.app && e.path === r.path && e.methods.includes(r.method));
  if (ex) {
    usedExemptions.add(ex);
    continue;
  }
  undocumented.push(r);
}
// An exemption that matches nothing is a stale decision: the route moved, or is no longer public.
const stale = exemptions.filter((e) => !usedExemptions.has(e) && !e.methods.some((m) => onDisk.some((r) => r.app === e.app && r.path === e.path && r.method === m)));
const exemptedButPrivate = exemptions.filter((e) => onDisk.some((r) => r.app === e.app && r.path === e.path && e.methods.includes(r.method) && !r.public));

// ─── report ──────────────────────────────────────────────────────────────────────────────────────
const specNames = specFiles.map((f) => basename(f)).join(", ");
console.log(`verify:openapi — ${documented.size} documented operations in ${specNames}; ${onDisk.length} route×method on disk (${onDisk.filter((r) => r.public).length} public), ${exemptions.length} exemptions`);
for (const p of problems) console.log(`  ! ${p}`);
for (const [key, d] of missing) console.log(`  - ${key}    documented in ${d.file}:${d.line} (${d.operationId}) — no such route on disk`);
for (const r of undocumented) console.log(`  + ${r.method} ${r.path}    ${r.file} gate=[${r.gate.join(",")}] — public and undocumented; document it or add an x-tokophi-route-exemptions entry with a reason`);
for (const e of stale) console.log(`  ? ${e.methods.join("/")} ${e.path}    exemption in ${e.file}:${e.line} matches no route on disk — delete it`);
for (const e of exemptedButPrivate) console.log(`  ? ${e.methods.join("/")} ${e.path}    exemption in ${e.file}:${e.line} names a route that is not public — the entry is a no-op; delete it`);

const red = problems.length + missing.length + undocumented.length + stale.length + exemptedButPrivate.length;
if (red) {
  console.log(`\n${red} problem(s).`);
  process.exit(1);
}
console.log("  ok — every documented operation exists; every public route is documented or explicitly exempted.");
